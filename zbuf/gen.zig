const std = @import("std");
const schema = @import("schema");
const defs = @import("buffers");

const FieldInfo = struct {
    id: u32,
    name: []const u8,
    ty: type,
    offset: u16,
};

pub fn main() !void {
    // Generator is a normal Zig program: compile-time schema info + runtime file output.
    @setEvalBranchQuota(20_000);
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    const alloc = gpa.allocator();

    var args = std.process.args();
    _ = args.next();
    const out_path = args.next() orelse "zbuf/buffers.gen.zig";

    // Write to a .tmp file first; rename to out_path only on success.
    // This guarantees the final file is always complete: a partial write
    // (crash, OOM, Ctrl-C) leaves the .tmp behind and the old .gen.zig intact.
    const tmp_path = try std.fmt.allocPrint(alloc, "{s}.tmp", .{out_path});
    defer alloc.free(tmp_path);
    errdefer std.fs.cwd().deleteFile(tmp_path) catch {};

    {
        var file = try std.fs.cwd().createFile(tmp_path, .{ .truncate = true });
        defer file.close();

        var buf: [4096]u8 = undefined;
        var fw = std.fs.File.Writer.init(file, &buf);
        var w = &fw.interface;
        // File header + imports used by all generated code.
        try w.writeAll("// This file is generated by zbuf/gen.zig. Do not edit.\n");
        // const ts_line = try formatTimestamp(alloc);
        // defer alloc.free(ts_line);
        // try w.print("// Generated at: {s}\n", .{ts_line});
        try w.writeAll("const std = @import(\"std\");\n");
        try w.writeAll("const zbuf = @import(\"zbuf\").zbuf;\n\n");
        try w.writeAll("pub const Error = std.mem.Allocator.Error || zbuf.Error;\n");
        try w.writeAll("pub const NullOffset: u32 = zbuf.NullOffset;\n\n");
        try w.writeAll("pub const Ownership = zbuf.Ownership;\n\n");

        // Emit code for each table declared in the input buffers.zig.
        // Enums must come first — table fields may reference enum types by name.
        try emitEnumTypes(w);
        try emitTailHelpers(w);
        try emitMessageParser(w);

        inline for (defs.tables) |entry| {
            try emitTable(alloc, entry.name, entry.ty, entry.id, w);
        }
        try w.flush();
    } // file.close() fires here, before rename

    try std.fs.cwd().rename(tmp_path, out_path);
    std.debug.print("generated {s}\n", .{out_path});
}

fn formatTimestamp(alloc: std.mem.Allocator) ![]const u8 {
    const ts = std.time.timestamp();
    if (ts < 0) {
        return std.fmt.allocPrint(alloc, "unknown", .{});
    }
    const secs = @as(u64, @intCast(ts));
    const epoch_seconds = std.time.epoch.EpochSeconds{ .secs = secs };
    const day = epoch_seconds.getEpochDay();
    const day_seconds = epoch_seconds.getDaySeconds();
    const year_day = day.calculateYearDay();
    const month_day = year_day.calculateMonthDay();

    const year = year_day.year;
    const month = month_day.month.numeric();
    const day_of_month: u8 = @intCast(month_day.day_index + 1);
    const hour = day_seconds.getHoursIntoDay();
    const minute = day_seconds.getMinutesIntoHour();
    const second = day_seconds.getSecondsIntoMinute();

    return std.fmt.allocPrint(
        alloc,
        "{d:0>4}-{d:0>2}-{d:0>2} {d:0>2}:{d:0>2}:{d:0>2} UTC",
        .{ year, month, day_of_month, hour, minute, second },
    );
}

fn tableNameForType(comptime T: type) []const u8 {
    // Resolve a schema table type to its exported name.
    inline for (defs.tables) |entry| {
        if (entry.ty == T) return entry.name;
    }
    @compileError("unknown table type");
}

// Walk all `pub const` declarations in buffers.zig to find enum-def types
// (those produced by schema.EnumDef). No explicit registry required.
fn isEnumDefType(comptime T: type) bool {
    const ti = @typeInfo(T);
    if (ti != .@"struct") return false;
    return @hasDecl(T, "schema_variants");
}

fn enumNameForType(comptime T: type) []const u8 {
    // Resolve a schema enum-def type to the `pub const` name it was bound to
    // in buffers.zig. The generator emits {Name}Enum for each.
    const decls = @typeInfo(defs).@"struct".decls;
    inline for (decls) |d| {
        const Field = @TypeOf(@field(defs, d.name));
        if (Field == type) {
            const DeclT = @field(defs, d.name);
            if (DeclT == T) return d.name;
        }
    }
    @compileError("enum type not found as a `pub const` in buffers.zig");
}

fn emitEnumTypes(w: anytype) !void {
    const decls = @typeInfo(defs).@"struct".decls;
    inline for (decls) |d| {
        const Field = @TypeOf(@field(defs, d.name));
        if (Field != type) continue;
        const DeclT = @field(defs, d.name);
        if (!comptime isEnumDefType(DeclT)) continue;

        // Compile-time validation: tags fit in u8 and are unique.
        const variants = comptime schema.enumVariants(DeclT);
        comptime {
            for (variants, 0..) |v, i| {
                if (v.tag >= 256) @compileError("enum tag exceeds u8 range");
                for (variants[i + 1 ..]) |o| {
                    if (o.tag == v.tag) @compileError("duplicate enum tag");
                }
            }
        }
        try w.print("pub const {s}Enum = enum(u8) {{\n", .{d.name});
        inline for (variants) |v| {
            try w.print("    {s} = {d},\n", .{ v.name, v.tag });
        }
        try w.writeAll("    _,\n");
        try w.writeAll("};\n\n");
    }
}

fn boolBitWidthForKind(comptime k: schema.Kind) u16 {
    return switch (k) {
        .b64 => 64,
        else => @compileError("bool backing field must be B64"),
    };
}

fn arrayElemSizeForKind(comptime k: schema.Kind) u16 {
    return switch (k) {
        .u16 => 2,
        .u32 => 4,
        .u64, .b64 => 8,
        .table => 4, // table arrays store u32 offsets
        else => @compileError("unsupported array child kind"),
    };
}

fn scalarTypeNameForKind(comptime k: schema.Kind) []const u8 {
    return switch (k) {
        .u16 => "u16",
        .u32 => "u32",
        .u64, .b64 => "u64",
        else => @compileError("not a scalar array child kind"),
    };
}

fn scalarReadFnForKind(comptime k: schema.Kind) []const u8 {
    return switch (k) {
        .u16 => "readU16",
        .u32 => "readU32",
        .u64, .b64 => "readU64",
        else => @compileError("not a scalar array child kind"),
    };
}

fn findFieldInfoById(comptime infos: anytype, comptime field_id: u32) ?FieldInfo {
    inline for (infos) |info| {
        if (info.id == field_id) return info;
    }
    return null;
}

fn requireBoolLayoutValid(comptime infos: anytype) void {
    // Pass 1: walk every field and only act on Bool logical fields.
    // For each Bool, validate that its backing field exists, has a bitset kind,
    // and that the requested bit index is within that bitset's width.
    inline for (infos, 0..) |info, i| {
        if (comptime schema.kindOf(info.ty) != .bool) continue;

        const bits_field_id = schema.boolFieldId(info.ty);
        const bit_index = schema.boolBitIndex(info.ty);
        const bits_field = findFieldInfoById(infos, bits_field_id) orelse
            @compileError("Bool field references unknown backing field id");
        const bits_kind = schema.kindOf(bits_field.ty);
        const width = boolBitWidthForKind(bits_kind);
        if (bit_index >= width) {
            @compileError("Bool field bit index exceeds backing field width");
        }
        // Pass 2 (for this Bool): compare against only the *later* fields.
        // This avoids duplicate reporting and still checks every pair exactly once.
        //
        // If another Bool uses the same (field_id, bit), both would alias the same
        // underlying bit, which is ambiguous. Reject that schema at compile time.
        inline for (infos[i + 1 ..]) |other| {
            if (comptime schema.kindOf(other.ty) != .bool) continue;
            if (schema.boolFieldId(other.ty) != bits_field_id) continue;
            if (schema.boolBitIndex(other.ty) != bit_index) continue;
            @compileError("duplicate Bool mapping to same backing field bit");
        }
    }
}

fn emitTable(alloc: std.mem.Allocator, comptime table_name: []const u8, comptime T: type, comptime table_id: u16, w: anytype) !void {
    // Compile-time layout calculation: field order, slot offsets, and header size.
    const layout = comptime blk: {
        const fields = schema.sortFieldsById(T.fields);
        var offset: u16 = 4; // version + size_bytes
        var infos: [fields.len]FieldInfo = undefined;
        for (fields, 0..) |f, i| {
            infos[i] = .{ .id = f.id, .name = f.name, .ty = f.ty, .offset = offset };
            offset += schema.slotSize(f.ty);
        }
        break :blk .{ .infos = infos, .size_bytes = offset };
    };
    const infos = layout.infos;
    const size_bytes: u16 = layout.size_bytes;
    comptime requireBoolLayoutValid(infos);

    // -------------------------
    // Struct type (owned, allocator-backed)
    // -------------------------
    try emitStructType(alloc, table_name, infos, w);

    // -------------------------
    // Reader type
    // -------------------------
    try w.print("pub const {s}Reader = struct {{\n", .{table_name});
    try w.writeAll("    const Self = @This();\n");
    try w.writeAll("    buf: []const u8,\n");
    try w.writeAll("    base: u32,\n");
    try w.writeAll("    size_bytes: u16,\n\n");

    try w.print("    pub const VERSION: u16 = {d};\n", .{1});
    try w.print("    pub const TABLE_ID: u16 = {d};\n", .{table_id});
    try w.print("    pub const SIZE_BYTES: u16 = {d};\n\n", .{size_bytes});

    try w.writeAll("    pub fn parseRoot(buf: []const u8) Error!Self {\n");
    try w.writeAll("        const tail = try zbuf.readMessageTail(buf);\n");
    try w.writeAll("        if (tail.table_id != TABLE_ID) return zbuf.Error.Invalid;\n");
    try w.writeAll("        const payload_buf = buf[0 .. buf.len - zbuf.message_tail_size];\n");
    try w.writeAll("        return init(payload_buf, tail.offset);\n");
    try w.writeAll("    }\n\n");

    // init() validates that header fits in the buffer; field accessors are bounds-checked.
    try w.writeAll("    pub fn init(buf: []const u8, base: u32) Error!Self {\n");
    try w.writeAll("        if (@as(usize, base) + 4 > buf.len) return zbuf.Error.OutOfBounds;\n");
    try w.writeAll("        const size_bytes = try zbuf.readU16(buf, @as(usize, base + 2));\n");
    try w.writeAll("        if (@as(usize, base) + @as(usize, size_bytes) > buf.len) return zbuf.Error.OutOfBounds;\n");
    try w.writeAll("        return .{ .buf = buf, .base = base, .size_bytes = size_bytes };\n");
    try w.writeAll("    }\n\n");

    // Field accessors: read from fixed header slots, using size_bytes for compatibility.
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .u16 => {
                // Scalars are stored inline in the fixed header.
                try w.print("    pub fn {s}(self: Self) u16 {{\n", .{name_camel});
                try emitScalarGetter(w, info.offset, 2, "readU16");
                try w.writeAll("    }\n\n");
            },
            .u32 => {
                // Scalars are stored inline in the fixed header.
                try w.print("    pub fn {s}(self: Self) u32 {{\n", .{name_camel});
                try emitScalarGetter(w, info.offset, 4, "readU32");
                try w.writeAll("    }\n\n");
            },
            .u64 => {
                // Scalars are stored inline in the fixed header.
                try w.print("    pub fn {s}(self: Self) u64 {{\n", .{name_camel});
                try emitScalarGetter(w, info.offset, 8, "readU64");
                try w.writeAll("    }\n\n");
            },
            .b64 => {
                try w.print("    pub fn {s}(self: Self) u64 {{\n", .{name_camel});
                try emitBitsetGetter(w, info.offset);
                try w.writeAll("    }\n\n");
                try w.print("    pub fn {s}HasBit(self: Self, bit_index: u32) bool {{\n", .{name_camel});
                try emitBitsetHasBit(w, info.offset);
                try w.writeAll("    }\n\n");
            },
            .bytes => {
                // Bytes are stored as (off,len) in the header, pointing into the buffer.
                try w.print("    pub fn {s}(self: Self) []const u8 {{\n", .{name_camel});
                try emitBytesGetter(w, info.offset);
                try w.writeAll("    }\n\n");
            },
            .array => {
                // Arrays are stored as (index_off,count). For table arrays, index_off points
                // to u32 offsets. For scalar arrays, index_off points to packed scalar elements.
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                const elem_size = arrayElemSizeForKind(child_kind);
                const name_camel_arr = try schema.camelName(alloc, info.name);
                defer alloc.free(name_camel_arr);
                switch (child_kind) {
                    .table => {
                        const child_name = tableNameForType(child);
                        // Table arrays store u32 offsets (4 bytes each): same slice approach as scalar arrays.
                        try w.print("    fn {s}Slice(self: Self) []const u8 {{\n", .{name_camel_arr});
                        try emitScalarArraySliceGetter(w, info.offset, elem_size);
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}Len(self: Self) u32 {{\n", .{name_camel_arr});
                        try w.print("        return @intCast(self.{s}Slice().len / {d});\n", .{ name_camel_arr, elem_size });
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}At(self: Self, i: u32) Error!{s}Reader {{\n", .{ name_camel_arr, child_name });
                        try w.print("        const s = self.{s}Slice();\n", .{name_camel_arr});
                        try w.print("        const off = @as(usize, i) * {d};\n", .{elem_size});
                        try w.print("        if (off + {d} > s.len) return zbuf.Error.OutOfBounds;\n", .{elem_size});
                        try w.writeAll("        const child_off = zbuf.readU32(s, off) catch unreachable;\n");
                        try w.print("        return {s}Reader.init(self.buf, child_off);\n", .{child_name});
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}AtClone(self: Self, alloc: std.mem.Allocator, i: u32) Error!{s}Buffer {{\n", .{ name_camel_arr, child_name });
                        try w.print("        const child = try self.{s}At(i);\n", .{name_camel_arr});
                        try w.writeAll("        var out = std.ArrayList(u8).empty;\n");
                        try w.writeAll("        errdefer out.deinit(alloc);\n");
                        try w.print("        const child_buf = try {s}Buffer.initWithOffset(alloc, @constCast(self.buf), child.base, .borrowed);\n", .{child_name});
                        try w.writeAll("        const child_off = try child_buf.cloneInto(alloc, &out);\n");
                        try w.print("        try addTail(alloc, &out, {s}Reader, child_off);\n", .{child_name});
                        try w.writeAll("        const bytes = try out.toOwnedSlice(alloc);\n");
                        try w.print("        return {s}Buffer.initWithTail(alloc, bytes, .owned);\n", .{child_name});
                        try w.writeAll("    }\n\n");
                    },
                    .u16, .u32, .u64 => {
                        // Scalar arrays: validate backing region once via *Slice(), then delegate.
                        const scalar_ty = scalarTypeNameForKind(child_kind);
                        const scalar_read_fn = scalarReadFnForKind(child_kind);
                        try w.print("    fn {s}Slice(self: Self) []const u8 {{\n", .{name_camel_arr});
                        try emitScalarArraySliceGetter(w, info.offset, elem_size);
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}Len(self: Self) u32 {{\n", .{name_camel_arr});
                        try w.print("        return @intCast(self.{s}Slice().len / {d});\n", .{ name_camel_arr, elem_size });
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}At(self: Self, i: u32) Error!{s} {{\n", .{ name_camel_arr, scalar_ty });
                        try w.print("        const s = self.{s}Slice();\n", .{name_camel_arr});
                        try w.print("        const off = @as(usize, i) * {d};\n", .{elem_size});
                        try w.print("        if (off + {d} > s.len) return zbuf.Error.OutOfBounds;\n", .{elem_size});
                        try w.print("        return zbuf.{s}(s, off) catch unreachable;\n", .{scalar_read_fn});
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}ToSliceAlloc(self: Self, alloc: std.mem.Allocator) Error![]{s} {{\n", .{ name_camel_arr, scalar_ty });
                        try w.print("        const raw = self.{s}Slice();\n", .{name_camel_arr});
                        try w.print("        const count = raw.len / {d};\n", .{elem_size});
                        try w.print("        const out = try alloc.alloc({s}, count);\n", .{scalar_ty});
                        try w.writeAll("        errdefer alloc.free(out);\n");
                        try w.writeAll("        for (out, 0..) |*v, i| {\n");
                        try w.print("            v.* = zbuf.{s}(raw, i * {d}) catch unreachable;\n", .{ scalar_read_fn, elem_size });
                        try w.writeAll("        }\n");
                        try w.writeAll("        return out;\n");
                        try w.writeAll("    }\n\n");
                    },
                    .b64 => {
                        // b64 arrays keep the old per-element approach (no *Slice / ToSliceAlloc).
                        const scalar_ty = scalarTypeNameForKind(child_kind);
                        const scalar_read_fn = scalarReadFnForKind(child_kind);
                        try w.print("    pub fn {s}Len(self: Self) u32 {{\n", .{name_camel_arr});
                        try emitArrayLenGetter(w, info.offset, elem_size);
                        try w.writeAll("    }\n\n");
                        try w.print("    pub fn {s}At(self: Self, i: u32) Error!{s} {{\n", .{ name_camel_arr, scalar_ty });
                        try emitArrayAtGetterScalar(w, info.offset, elem_size, scalar_read_fn);
                        try w.writeAll("    }\n\n");
                    },
                    else => @compileError("unsupported array child kind"),
                }
            },
            .table => {
                const child_name = tableNameForType(info.ty);
                try w.print("    pub fn {s}(self: Self) ?{s}Reader {{\n", .{ name_camel, child_name });
                try emitTableGetter(w, info.offset, child_name);
                try w.writeAll("    }\n\n");
            },
            .bool => {
                const bits_field = findFieldInfoById(infos, schema.boolFieldId(info.ty)) orelse
                    @compileError("Bool field references unknown backing field id");
                const bit_index: u16 = schema.boolBitIndex(info.ty);
                try w.print("    pub fn {s}(self: Self) bool {{\n", .{name_camel});
                try emitBoolGetter(w, bits_field.offset, bit_index);
                try w.writeAll("    }\n\n");
            },
            .enum_ => {
                const enum_def = comptime schema.enumDefOf(info.ty);
                const enum_name = enumNameForType(enum_def);
                try w.print("    pub fn {s}(self: Self) {s}Enum {{\n", .{ name_camel, enum_name });
                try emitEnumGetter(w, info.offset);
                try w.writeAll("    }\n\n");
            },
        }
    }

    // verify() provides optional bounds checking of nested data.
    const verify_needs_header_end = comptime blk: {
        var needed = false;
        for (infos) |info| {
            switch (schema.kindOf(info.ty)) {
                .bytes, .array, .table => {
                    needed = true;
                    break;
                },
                else => {},
            }
        }
        break :blk needed;
    };
    try w.writeAll("    pub fn verify(self: Self) Error!void {\n");
    try w.writeAll("        if (@as(usize, self.base) + @as(usize, self.size_bytes) > self.buf.len) return zbuf.Error.OutOfBounds;\n");
    if (verify_needs_header_end) {
        try w.writeAll("        const header_end = @as(u32, self.base) + self.size_bytes;\n");
    }
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .bytes => {
                try emitBytesVerify(w, info.offset);
            },
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                const elem_size = arrayElemSizeForKind(child_kind);
                const name_camel_arr = try schema.camelName(alloc, info.name);
                defer alloc.free(name_camel_arr);
                try emitArrayVerifyRange(w, info.offset, elem_size);
                if (child_kind == .table) {
                    try w.print("        const count_{s}: u32 = self.{s}Len();\n", .{ name_camel_arr, name_camel_arr });
                    try w.print("        var i_{s}: u32 = 0;\n", .{name_camel_arr});
                    try w.print("        while (i_{s} < count_{s}) : (i_{s} += 1) {{\n", .{ name_camel_arr, name_camel_arr, name_camel_arr });
                    try w.print("            const child_view = try self.{s}At(i_{s});\n", .{ name_camel_arr, name_camel_arr });
                    try w.writeAll("            try child_view.verify();\n");
                    try w.writeAll("        }\n");
                }
            },
            .table => {
                const name = try schema.camelName(alloc, info.name);
                defer alloc.free(name);
                try w.print("        if (self.{s}()) |child_view| {{\n", .{name});
                try w.writeAll("            try child_view.verify();\n");
                try w.writeAll("        }\n");
            },
            else => {},
        }
    }
    try w.writeAll("    }\n");
    try w.writeAll("};\n\n");

    // -------------------------
    // Writer type
    // -------------------------
    try w.print("pub const {s}Buffer = struct {{\n", .{table_name});
    try w.writeAll("    alloc: std.mem.Allocator,\n");
    try w.writeAll("    offset: u32,\n");
    try w.writeAll("    bytes: ?[]u8,\n");
    try w.writeAll("    ownership: Ownership,\n");
    try w.writeAll("    has_tail: bool,\n");
    try w.writeAll("    pub fn initWithTail(alloc: std.mem.Allocator, bytes: []u8, ownership: Ownership) Error!@This() {\n");
    try w.writeAll("        const tail = try zbuf.readMessageTail(bytes);\n");
    try w.print("        if (tail.table_id != {s}Reader.TABLE_ID) return zbuf.Error.Invalid;\n", .{table_name});
    try w.print("        if (tail.table_version != {s}Reader.VERSION) return zbuf.Error.Invalid;\n", .{table_name});
    try w.writeAll("        return .{ .alloc = alloc, .offset = tail.offset, .bytes = bytes, .ownership = ownership, .has_tail = true };\n");
    try w.writeAll("    }\n");
    try w.writeAll("    pub fn initWithOffset(alloc: std.mem.Allocator, bytes: []u8, offset: u32, ownership: Ownership) Error!@This() {\n");
    try w.writeAll("        return .{ .alloc = alloc, .offset = offset, .bytes = bytes, .ownership = ownership, .has_tail = false };\n");
    try w.writeAll("    }\n");
    try w.print("    pub fn initReader(self: @This()) Error!{s}Reader {{\n", .{table_name});
    try w.writeAll("        const payload = self.bytes orelse return zbuf.Error.Invalid;\n");
    try w.print("        return {s}Reader.init(payload, self.offset);\n", .{table_name});
    try w.writeAll("    }\n");
    try w.writeAll("    pub fn cloneInto(self: @This(), alloc: std.mem.Allocator, out: *std.ArrayList(u8)) Error!u32 {\n");
    try w.writeAll("        const reader = try self.initReader();\n");
    try w.print("        var writer = try {s}Writer.initWithBuf(alloc, out);\n", .{table_name});
    inline for (infos) |info| {
        const name_camel = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(name_camel);
        const name_lower = try schema.camelName(alloc, info.name);
        defer alloc.free(name_lower);
        switch (comptime schema.kindOf(info.ty)) {
            .u16, .u32, .u64, .bytes, .bool, .enum_ => {
                try w.print("        try writer.set{s}(reader.{s}());\n", .{ name_camel, name_lower });
            },
            .b64 => {
                try w.print("        try writer.{s}Set(reader.{s}());\n", .{ name_lower, name_lower });
            },
            .table => {
                const child_name = tableNameForType(info.ty);
                try w.print("        if (reader.{s}()) |child| {{\n", .{name_lower});
                try w.print("            const child_buf = try {s}Buffer.initWithOffset(alloc, @constCast(reader.buf), child.base, .borrowed);\n", .{child_name});
                try w.writeAll("            const child_off = try child_buf.cloneInto(alloc, out);\n");
                try w.print("            try writer.set{s}(child_off);\n", .{name_camel});
                try w.writeAll("        }\n");
            },
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                const name_camel_arr = try schema.camelName(alloc, info.name);
                defer alloc.free(name_camel_arr);
                switch (child_kind) {
                    .table => {
                        const child_name = tableNameForType(child);
                        try w.print("        const count_{s}: u32 = reader.{s}Len();\n", .{ name_camel_arr, name_camel_arr });
                        try w.print("        if (count_{s} != 0) {{\n", .{name_camel_arr});
                        try w.print("            var child_offsets_{s} = try alloc.alloc(u32, @intCast(count_{s}));\n", .{ name_camel_arr, name_camel_arr });
                        try w.print("            defer alloc.free(child_offsets_{s});\n", .{name_camel_arr});
                        try w.print("            var i_{s}: u32 = 0;\n", .{name_camel_arr});
                        try w.print("            while (i_{s} < count_{s}) : (i_{s} += 1) {{\n", .{ name_camel_arr, name_camel_arr, name_camel_arr });
                        try w.print("                const child = try reader.{s}At(i_{s});\n", .{ name_camel_arr, name_camel_arr });
                        try w.print("                const child_buf = try {s}Buffer.initWithOffset(alloc, @constCast(reader.buf), child.base, .borrowed);\n", .{child_name});
                        try w.print("                child_offsets_{s}[@intCast(i_{s})] = try child_buf.cloneInto(alloc, out);\n", .{ name_camel_arr, name_camel_arr });
                        try w.writeAll("            }\n");
                        try w.print("            try writer.set{s}(child_offsets_{s});\n", .{ name_camel, name_camel_arr });
                        try w.writeAll("        }\n");
                    },
                    .u16, .u32, .u64 => {
                        // Use ToSliceAlloc: validates once, single allocation, single copy.
                        try w.print("        const values_{s} = try reader.{s}ToSliceAlloc(alloc);\n", .{ name_camel_arr, name_camel_arr });
                        try w.print("        defer alloc.free(values_{s});\n", .{name_camel_arr});
                        try w.print("        if (values_{s}.len > 0) try writer.set{s}(values_{s});\n", .{ name_camel_arr, name_camel, name_camel_arr });
                    },
                    .b64 => {
                        // b64 arrays: no ToSliceAlloc, use element-by-element loop.
                        const scalar_ty = scalarTypeNameForKind(child_kind);
                        try w.print("        const count_{s}: u32 = reader.{s}Len();\n", .{ name_camel_arr, name_camel_arr });
                        try w.print("        if (count_{s} != 0) {{\n", .{name_camel_arr});
                        try w.print("            var values_{s} = try alloc.alloc({s}, @intCast(count_{s}));\n", .{ name_camel_arr, scalar_ty, name_camel_arr });
                        try w.print("            defer alloc.free(values_{s});\n", .{name_camel_arr});
                        try w.print("            var i_{s}: u32 = 0;\n", .{name_camel_arr});
                        try w.print("            while (i_{s} < count_{s}) : (i_{s} += 1) {{\n", .{ name_camel_arr, name_camel_arr, name_camel_arr });
                        try w.print("                values_{s}[@intCast(i_{s})] = try reader.{s}At(i_{s});\n", .{ name_camel_arr, name_camel_arr, name_camel_arr, name_camel_arr });
                        try w.writeAll("            }\n");
                        try w.print("            try writer.set{s}(values_{s});\n", .{ name_camel, name_camel_arr });
                        try w.writeAll("        }\n");
                    },
                    else => @compileError("unsupported array child kind"),
                }
            },
        }
    }
    try w.writeAll("        const result = try writer.finish();\n");
    try w.writeAll("        return result.offset;\n");
    try w.writeAll("    }\n");
    try w.writeAll("    pub fn deinit(self: *@This()) void {\n");
    try w.writeAll("        if (self.bytes) |bytes| {\n");
    try w.writeAll("            if (self.ownership == .owned) self.alloc.free(bytes);\n");
    try w.writeAll("            self.bytes = null;\n");
    try w.writeAll("            self.ownership = .borrowed;\n");
    try w.writeAll("        }\n");
    try w.writeAll("    }\n");
    try w.writeAll("};\n\n");

    try w.print("pub const {s}Writer = struct {{\n", .{table_name});
    try w.writeAll("    const Self = @This();\n");
    try w.writeAll("    buf: ?*std.ArrayList(u8),\n");
    try w.writeAll("    owns_buf: bool,\n");
    try w.writeAll("    alloc: std.mem.Allocator,\n");
    try w.writeAll("    base: u32,\n\n");
    try w.print("    pub const VERSION: u16 = {d};\n", .{1});
    try w.print("    pub const TABLE_ID: u16 = {d};\n", .{table_id});
    try w.print("    pub const SIZE_BYTES: u16 = {d};\n\n", .{size_bytes});

    try w.writeAll("    fn bufMut(self: *Self) *std.ArrayList(u8) {\n");
    try w.writeAll("        return self.buf orelse @panic(\"zbuf writer missing buffer\");\n");
    try w.writeAll("    }\n\n");

    // initWithBuf() reserves the fixed header and writes version + size_bytes.
    try w.writeAll("    pub fn initWithBuf(alloc: std.mem.Allocator, buf: *std.ArrayList(u8)) Error!Self {\n");
    try w.writeAll("        const base = try zbuf.reserveHeader(buf, alloc, SIZE_BYTES);\n");
    try w.writeAll("        try zbuf.writeU16At(buf.items, @as(usize, base), VERSION);\n");
    try w.writeAll("        try zbuf.writeU16At(buf.items, @as(usize, base + 2), SIZE_BYTES);\n");
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .table => {
                try w.print("        try zbuf.patchU32(buf.items, base + {d}, zbuf.NullOffset);\n", .{info.offset});
            },
            else => {},
        }
    }
    try w.writeAll("        return .{ .buf = buf, .owns_buf = false, .alloc = alloc, .base = base };\n");
    try w.writeAll("    }\n\n");

    // init() owns its internal buffer and returns encoded bytes from finish().
    try w.writeAll("    pub fn init(alloc: std.mem.Allocator) Error!Self {\n");
    try w.writeAll("        const owned = try alloc.create(std.ArrayList(u8));\n");
    try w.writeAll("        owned.* = .empty;\n");
    try w.writeAll("        errdefer alloc.destroy(owned);\n");
    try w.writeAll("        const base = try zbuf.reserveHeader(owned, alloc, SIZE_BYTES);\n");
    try w.writeAll("        try zbuf.writeU16At(owned.items, @as(usize, base), VERSION);\n");
    try w.writeAll("        try zbuf.writeU16At(owned.items, @as(usize, base + 2), SIZE_BYTES);\n");
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .table => {
                try w.print("        try zbuf.patchU32(owned.items, base + {d}, zbuf.NullOffset);\n", .{info.offset});
            },
            else => {},
        }
    }
    try w.writeAll("        return .{ .buf = owned, .owns_buf = true, .alloc = alloc, .base = base };\n");
    try w.writeAll("    }\n\n");

    inline for (infos) |info| {
        const name_camel = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(name_camel);
        const name_lower = try schema.camelName(alloc, info.name);
        defer alloc.free(name_lower);
        switch (comptime schema.kindOf(info.ty)) {
            .u16 => {
                // Patch inline scalar slot.
                try w.print("    pub fn set{s}(self: *Self, v: u16) Error!void {{\n", .{name_camel});
                try w.writeAll("        const out = self.bufMut();\n");
                try w.print("        try zbuf.patchU16(out.items, self.base + {d}, v);\n", .{info.offset});
                try w.writeAll("    }\n\n");
            },
            .u32 => {
                // Patch inline scalar slot.
                try w.print("    pub fn set{s}(self: *Self, v: u32) Error!void {{\n", .{name_camel});
                try w.writeAll("        const out = self.bufMut();\n");
                try w.print("        try zbuf.patchU32(out.items, self.base + {d}, v);\n", .{info.offset});
                try w.writeAll("    }\n\n");
            },
            .u64 => {
                // Patch inline scalar slot.
                try w.print("    pub fn set{s}(self: *Self, v: u64) Error!void {{\n", .{name_camel});
                try w.writeAll("        const out = self.bufMut();\n");
                try w.print("        try zbuf.patchU64(out.items, self.base + {d}, v);\n", .{info.offset});
                try w.writeAll("    }\n\n");
            },
            .b64 => {
                try w.print("    pub fn {s}Set(self: *Self, v: u64) Error!void {{\n", .{name_lower});
                try emitBitsetSetter(w, info.offset);
                try w.writeAll("    }\n\n");
                try w.print("    pub fn {s}SetBit(self: *Self, bit_index: u32) Error!void {{\n", .{name_lower});
                try emitBitsetSetBit(w, info.offset);
                try w.writeAll("    }\n\n");
                try w.print("    pub fn {s}ClearBit(self: *Self, bit_index: u32) Error!void {{\n", .{name_lower});
                try emitBitsetClearBit(w, info.offset);
                try w.writeAll("    }\n\n");
                try w.print("    pub fn {s}HasBit(self: *Self, bit_index: u32) Error!bool {{\n", .{name_lower});
                try emitBitsetHasBitBuilder(w, info.offset);
                try w.writeAll("    }\n\n");
            },
            .bytes => {
                // Append payload and patch (off,len) in the header (offsets are payload-relative).
                try w.print("    pub fn set{s}(self: *Self, data: []const u8) Error!void {{\n", .{name_camel});
                try w.writeAll("        const out = self.bufMut();\n");
                try w.writeAll("        if (data.len == 0) {\n");
                try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset});
                try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset + 4});
                try w.writeAll("            return;\n");
                try w.writeAll("        }\n");
                try w.writeAll("        const abs_off = try zbuf.appendBytes(out, self.alloc, data);\n");
                try w.writeAll("        const off = abs_off;\n");
                try w.print("        try zbuf.patchU32(out.items, self.base + {d}, off);\n", .{info.offset});
                try w.print("        try zbuf.patchU32(out.items, self.base + {d}, @as(u32, @intCast(data.len)));\n", .{info.offset + 4});
                try w.writeAll("    }\n\n");
            },
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .table, .u32 => {
                        // Append u32 data and patch (index_off,count) in the header.
                        try w.print("    pub fn set{s}(self: *Self, values: []const u32) Error!void {{\n", .{name_camel});
                        try w.writeAll("        const out = self.bufMut();\n");
                        try w.writeAll("        if (values.len == 0) {\n");
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset});
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset + 4});
                        try w.writeAll("            return;\n");
                        try w.writeAll("        }\n");
                        try w.writeAll("        const abs_index_off = try zbuf.appendU32Slice(out, self.alloc, values);\n");
                        try w.writeAll("        const index_off = abs_index_off;\n");
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, index_off);\n", .{info.offset});
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, @as(u32, @intCast(values.len)));\n", .{info.offset + 4});
                        try w.writeAll("    }\n\n");
                    },
                    .u16 => {
                        // Append u16 data and patch (index_off,count) in the header.
                        try w.print("    pub fn set{s}(self: *Self, values: []const u16) Error!void {{\n", .{name_camel});
                        try w.writeAll("        const out = self.bufMut();\n");
                        try w.writeAll("        if (values.len == 0) {\n");
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset});
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset + 4});
                        try w.writeAll("            return;\n");
                        try w.writeAll("        }\n");
                        try w.writeAll("        const abs_index_off = try zbuf.appendU16Slice(out, self.alloc, values);\n");
                        try w.writeAll("        const index_off = abs_index_off;\n");
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, index_off);\n", .{info.offset});
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, @as(u32, @intCast(values.len)));\n", .{info.offset + 4});
                        try w.writeAll("    }\n\n");
                    },
                    .u64, .b64 => {
                        // Append u64 data and patch (index_off,count) in the header.
                        try w.print("    pub fn set{s}(self: *Self, values: []const u64) Error!void {{\n", .{name_camel});
                        try w.writeAll("        const out = self.bufMut();\n");
                        try w.writeAll("        if (values.len == 0) {\n");
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset});
                        try w.print("            try zbuf.patchU32(out.items, self.base + {d}, 0);\n", .{info.offset + 4});
                        try w.writeAll("            return;\n");
                        try w.writeAll("        }\n");
                        try w.writeAll("        const abs_index_off = try zbuf.appendU64Slice(out, self.alloc, values);\n");
                        try w.writeAll("        const index_off = abs_index_off;\n");
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, index_off);\n", .{info.offset});
                        try w.print("        try zbuf.patchU32(out.items, self.base + {d}, @as(u32, @intCast(values.len)));\n", .{info.offset + 4});
                        try w.writeAll("    }\n\n");
                    },
                    else => @compileError("unsupported array child kind"),
                }
            },
            .table => {
                // Patch inline table offset slot.
                try w.print("    pub fn set{s}(self: *Self, child_off: u32) Error!void {{\n", .{name_camel});
                try w.writeAll("        const out = self.bufMut();\n");
                try w.print("        try zbuf.patchU32(out.items, self.base + {d}, child_off);\n", .{info.offset});
                try w.writeAll("    }\n\n");
            },
            .bool => {
                const bits_field = findFieldInfoById(infos, schema.boolFieldId(info.ty)) orelse
                    @compileError("Bool field references unknown backing field id");
                const bit_index: u16 = schema.boolBitIndex(info.ty);
                try w.print("    pub fn set{s}(self: *Self, v: bool) Error!void {{\n", .{name_camel});
                try emitBoolSetter(w, bits_field.offset, bit_index);
                try w.writeAll("    }\n\n");
            },
            .enum_ => {
                const enum_def = comptime schema.enumDefOf(info.ty);
                const enum_name = enumNameForType(enum_def);
                try w.print("    pub fn set{s}(self: *Self, v: {s}Enum) Error!void {{\n", .{ name_camel, enum_name });
                try emitEnumSetter(w, info.offset);
                try w.writeAll("    }\n\n");
            },
            // table handled above
        }
    }

    // set() applies multiple fields from a struct literal in one call.
    try w.writeAll("    pub fn set(self: *Self, values: anytype) Error!void {\n");
    try w.writeAll("        const Values = @TypeOf(values);\n");
    try w.writeAll("        if (@typeInfo(Values) != .@\"struct\") {\n");
    try w.writeAll("            @compileError(\"set() expects a struct literal like .{ .field = value }\");\n");
    try w.writeAll("        }\n");
    inline for (infos) |info| {
        const name_camel = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(name_camel);
        const name_lower = try schema.camelName(alloc, info.name);
        defer alloc.free(name_lower);
        switch (comptime schema.kindOf(info.ty)) {
            .b64 => {
                try w.print("        if (@hasField(Values, \"{s}\")) try self.{s}Set(@field(values, \"{s}\"));\n", .{ info.name, name_lower, info.name });
            },
            else => {
                try w.print("        if (@hasField(Values, \"{s}\")) try self.set{s}(@field(values, \"{s}\"));\n", .{ info.name, name_camel, info.name });
            },
        }
    }
    try w.writeAll("    }\n\n");

    try w.print("    pub fn finish(self: *Self) Error!{s}Buffer {{\n", .{table_name});
    try w.writeAll("        if (self.owns_buf) {\n");
    try w.writeAll("            const owned = self.buf orelse return zbuf.Error.Invalid;\n");
    try w.writeAll("            const bytes = try owned.toOwnedSlice(self.alloc);\n");
    try w.writeAll("            self.alloc.destroy(owned);\n");
    try w.writeAll("            self.buf = null;\n");
    try w.writeAll("            return .{ .alloc = self.alloc, .offset = self.base, .bytes = bytes, .ownership = .owned, .has_tail = false };\n");
    try w.writeAll("        }\n");
    try w.writeAll("        return .{ .alloc = self.alloc, .offset = self.base, .bytes = null, .ownership = .borrowed, .has_tail = false };\n");
    try w.writeAll("    }\n");
    try w.writeAll("\n");
    try w.print("    pub fn finishWithTail(self: *Self) Error!{s}Buffer {{\n", .{table_name});
    try w.writeAll("        const out = self.bufMut();\n");
    try w.writeAll("        try zbuf.appendMessageTail(out, self.alloc, TABLE_ID, VERSION, self.base);\n");
    try w.writeAll("        var result = try self.finish();\n");
    try w.writeAll("        result.has_tail = true;\n");
    try w.writeAll("        return result;\n");
    try w.writeAll("    }\n");
    try w.writeAll("\n");
    try w.writeAll("    pub fn deinit(self: *Self) void {\n");
    try w.writeAll("        if (self.owns_buf) {\n");
    try w.writeAll("            const owned = self.buf orelse return;\n");
    try w.writeAll("            owned.deinit(self.alloc);\n");
    try w.writeAll("            self.alloc.destroy(owned);\n");
    try w.writeAll("            self.buf = null;\n");
    try w.writeAll("            self.base = 0;\n");
    try w.writeAll("            self.owns_buf = false;\n");
    try w.writeAll("        }\n");
    try w.writeAll("    }\n");
    try w.writeAll("};\n\n");
}

// emitStructType emits {Name}Struct with fromReader(alloc, r) and deinit(self*, alloc).
// Fields are decoded into owned Zig values — no Reader needed after construction.
fn emitStructType(alloc: std.mem.Allocator, comptime table_name: []const u8, comptime infos: anytype, w: anytype) !void {
    try w.print("pub const {s}Struct = struct {{\n", .{table_name});

    // Field declarations with defaults.
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .u16 => try w.print("    {s}: u16 = 0,\n", .{info.name}),
            .u32 => try w.print("    {s}: u32 = 0,\n", .{info.name}),
            .u64 => try w.print("    {s}: u64 = 0,\n", .{info.name}),
            .b64 => try w.print("    {s}: u64 = 0,\n", .{info.name}),
            .bool => try w.print("    {s}: bool = false,\n", .{info.name}),
            .enum_ => {
                const enum_def = comptime schema.enumDefOf(info.ty);
                const enum_name = enumNameForType(enum_def);
                try w.print("    {s}: {s}Enum = @enumFromInt(0),\n", .{ info.name, enum_name });
            },
            .bytes => try w.print("    {s}: []const u8 = &.{{}},\n", .{info.name}),
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .u16 => try w.print("    {s}: []u16 = &.{{}},\n", .{info.name}),
                    .u32 => try w.print("    {s}: []u32 = &.{{}},\n", .{info.name}),
                    .u64, .b64 => try w.print("    {s}: []u64 = &.{{}},\n", .{info.name}),
                    .table => {
                        const child_name = tableNameForType(child);
                        try w.print("    {s}: []{s}Struct = &.{{}},\n", .{ info.name, child_name });
                    },
                    else => @compileError("unsupported array child kind in struct"),
                }
            },
            .table => {
                const child_name = tableNameForType(info.ty);
                try w.print("    {s}: ?{s}Struct = null,\n", .{ info.name, child_name });
            },
        }
    }

    // fromReaderValue: decode reader into owned struct by value (internal, used by fromReader and parent structs).
    try w.print("\n    fn fromReaderValue(alloc: std.mem.Allocator, r: {s}Reader) Error!{s}Struct {{\n", .{ table_name, table_name });

    // Step 1: inline-init scalars and bools (no allocation).
    try w.print("        var s = {s}Struct{{\n", .{table_name});
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .u16, .u32, .u64, .b64, .bool, .enum_ => {
                try w.print("            .{s} = r.{s}(),\n", .{ info.name, name_camel });
            },
            else => {},
        }
    }
    try w.writeAll("        };\n");

    // Step 2: errdefer before any allocation so partial failures are safe.
    try w.writeAll("        errdefer s.deinit(alloc);\n");

    // Step 3: bytes fields — dupe the slice.
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .bytes => {
                try w.print("        s.{s} = try alloc.dupe(u8, r.{s}());\n", .{ info.name, name_camel });
            },
            else => {},
        }
    }

    // Step 4: scalar array fields (u16/u32/u64 use ToSliceAlloc; b64 uses manual loop).
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .u16, .u32, .u64 => {
                        try w.print("        s.{s} = try r.{s}ToSliceAlloc(alloc);\n", .{ info.name, name_camel });
                    },
                    .b64 => {
                        // No ToSliceAlloc for b64 arrays: use element-by-element loop.
                        try w.writeAll("        {\n");
                        try w.print("            const _cnt = r.{s}Len();\n", .{name_camel});
                        try w.print("            s.{s} = try alloc.alloc(u64, @intCast(_cnt));\n", .{info.name});
                        try w.writeAll("            var _i: u32 = 0;\n");
                        try w.writeAll("            while (_i < _cnt) : (_i += 1) {\n");
                        try w.print("                s.{s}[@intCast(_i)] = try r.{s}At(_i);\n", .{ info.name, name_camel });
                        try w.writeAll("            }\n");
                        try w.writeAll("        }\n");
                    },
                    .table => {}, // handled in step 5
                    else => @compileError("unsupported array child kind in struct fromReader"),
                }
            },
            else => {},
        }
    }

    // Step 5: table array fields — alloc slice, zero-init, then fromReaderValue each child.
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                if (child_kind == .table) {
                    const child_name = tableNameForType(child);
                    try w.writeAll("        {\n");
                    try w.print("            const _cnt = r.{s}Len();\n", .{name_camel});
                    try w.print("            s.{s} = try alloc.alloc({s}Struct, @intCast(_cnt));\n", .{ info.name, child_name });
                    try w.print("            @memset(s.{s}, .{{}});\n", .{info.name});
                    try w.writeAll("            for (0.._cnt) |_i| {\n");
                    try w.print("                const _child = try r.{s}At(@intCast(_i));\n", .{name_camel});
                    try w.print("                s.{s}[_i] = try {s}Struct.fromReaderValue(alloc, _child);\n", .{ info.name, child_name });
                    try w.writeAll("            }\n");
                    try w.writeAll("        }\n");
                }
            },
            else => {},
        }
    }

    // Step 6: optional nested table fields.
    inline for (infos) |info| {
        const name_camel = try schema.camelName(alloc, info.name);
        defer alloc.free(name_camel);
        switch (comptime schema.kindOf(info.ty)) {
            .table => {
                const child_name = tableNameForType(info.ty);
                try w.print("        if (r.{s}()) |_child| {{\n", .{name_camel});
                try w.print("            s.{s} = try {s}Struct.fromReaderValue(alloc, _child);\n", .{ info.name, child_name });
                try w.writeAll("        }\n");
            },
            else => {},
        }
    }

    try w.writeAll("        return s;\n");
    try w.writeAll("    }\n");

    // fromReader: heap-allocate and decode reader into owned struct, returning a pointer.
    try w.print("\n    pub fn fromReader(alloc: std.mem.Allocator, r: {s}Reader) Error!*{s}Struct {{\n", .{ table_name, table_name });
    try w.print("        const ptr = try alloc.create({s}Struct);\n", .{table_name});
    try w.writeAll("        errdefer alloc.destroy(ptr);\n");
    try w.writeAll("        ptr.* = try fromReaderValue(alloc, r);\n");
    try w.writeAll("        return ptr;\n");
    try w.writeAll("    }\n\n");

    // deinit: free all allocated fields.
    const has_owned_fields = comptime blk: {
        for (infos) |info| {
            switch (schema.kindOf(info.ty)) {
                .bytes, .array, .table => break :blk true,
                else => {},
            }
        }
        break :blk false;
    };
    try w.print("    pub fn deinit(self: *{s}Struct, alloc: std.mem.Allocator) void {{\n", .{table_name});
    if (!has_owned_fields) {
        try w.writeAll("        _ = self;\n");
        try w.writeAll("        _ = alloc;\n");
    }
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .bytes => {
                try w.print("        alloc.free(self.{s});\n", .{info.name});
                try w.print("        self.{s} = &.{{}};\n", .{info.name});
            },
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .u16, .u32, .u64, .b64 => {
                        try w.print("        alloc.free(self.{s});\n", .{info.name});
                        try w.print("        self.{s} = &.{{}};\n", .{info.name});
                    },
                    .table => {
                        try w.print("        for (self.{s}) |*_b| _b.deinit(alloc);\n", .{info.name});
                        try w.print("        alloc.free(self.{s});\n", .{info.name});
                        try w.print("        self.{s} = &.{{}};\n", .{info.name});
                    },
                    else => @compileError("unsupported array child kind in struct deinit"),
                }
            },
            .table => {
                try w.print("        if (self.{s}) |*_bf| _bf.deinit(alloc);\n", .{info.name});
                try w.print("        self.{s} = null;\n", .{info.name});
            },
            else => {},
        }
    }
    try w.writeAll("    }\n");

    // destroy: free all owned fields and then free the struct itself (for heap-allocated structs from clone).
    try w.print("\n    pub fn destroy(self: *{s}Struct, alloc: std.mem.Allocator) void {{\n", .{table_name});
    try w.writeAll("        self.deinit(alloc);\n");
    try w.writeAll("        alloc.destroy(self);\n");
    try w.writeAll("    }\n");

    // cloneValue: deep-copy the struct by value (internal, used by clone and parent structs).
    try w.print("\n    fn cloneValue(self: {s}Struct, alloc: std.mem.Allocator) Error!{s}Struct {{\n", .{ table_name, table_name });

    // Step 1: inline-init scalars and bools (no allocation).
    try w.print("        var s = {s}Struct{{\n", .{table_name});
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .u16, .u32, .u64, .b64, .bool, .enum_ => {
                try w.print("            .{s} = self.{s},\n", .{ info.name, info.name });
            },
            else => {},
        }
    }
    try w.writeAll("        };\n");

    // Step 2: errdefer before any allocation so partial failures are safe.
    try w.writeAll("        errdefer s.deinit(alloc);\n");

    // Step 3: bytes fields — dupe the slice.
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .bytes => {
                try w.print("        s.{s} = try alloc.dupe(u8, self.{s});\n", .{ info.name, info.name });
            },
            else => {},
        }
    }

    // Step 4: scalar/b64 array fields — dupe the slice.
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .u16 => {
                        try w.print("        s.{s} = try alloc.dupe(u16, self.{s});\n", .{ info.name, info.name });
                    },
                    .u32 => {
                        try w.print("        s.{s} = try alloc.dupe(u32, self.{s});\n", .{ info.name, info.name });
                    },
                    .u64, .b64 => {
                        try w.print("        s.{s} = try alloc.dupe(u64, self.{s});\n", .{ info.name, info.name });
                    },
                    .table => {}, // handled in step 5
                    else => @compileError("unsupported array child kind in struct clone"),
                }
            },
            else => {},
        }
    }

    // Step 5: table array fields — alloc slice, then recursively clone each child by value.
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                if (child_kind == .table) {
                    const child_name = tableNameForType(child);
                    try w.writeAll("        {\n");
                    try w.print("            s.{s} = try alloc.alloc({s}Struct, self.{s}.len);\n", .{ info.name, child_name, info.name });
                    try w.print("            @memset(s.{s}, .{{}});\n", .{info.name});
                    try w.print("            for (self.{s}, 0..) |_child, _i| {{\n", .{info.name});
                    try w.print("                s.{s}[_i] = try _child.cloneValue(alloc);\n", .{info.name});
                    try w.writeAll("            }\n");
                    try w.writeAll("        }\n");
                }
            },
            else => {},
        }
    }

    // Step 6: optional nested table fields.
    inline for (infos) |info| {
        switch (comptime schema.kindOf(info.ty)) {
            .table => {
                try w.print("        if (self.{s}) |_child| {{\n", .{info.name});
                try w.print("            s.{s} = try _child.cloneValue(alloc);\n", .{info.name});
                try w.writeAll("        }\n");
            },
            else => {},
        }
    }

    try w.writeAll("        return s;\n");
    try w.writeAll("    }\n");

    // clone: heap-allocate a deep copy of the struct, returning a pointer.
    try w.print("\n    pub fn clone(self: {s}Struct, alloc: std.mem.Allocator) Error!*{s}Struct {{\n", .{ table_name, table_name });
    try w.print("        const ptr = try alloc.create({s}Struct);\n", .{table_name});
    try w.writeAll("        errdefer alloc.destroy(ptr);\n");
    try w.writeAll("        ptr.* = try self.cloneValue(alloc);\n");
    try w.writeAll("        return ptr;\n");
    try w.writeAll("    }\n");

    // marshalTo: serialize struct fields into a shared output buffer, return offset.
    try w.print("\n    pub fn marshalTo(self: {s}Struct, alloc: std.mem.Allocator, out: *std.ArrayList(u8)) Error!u32 {{\n", .{table_name});
    try w.print("        var writer = try {s}Writer.initWithBuf(alloc, out);\n", .{table_name});
    inline for (infos) |info| {
        const name_camel = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(name_camel);
        const name_lower = try schema.camelName(alloc, info.name);
        defer alloc.free(name_lower);
        switch (comptime schema.kindOf(info.ty)) {
            .u16, .u32, .u64, .bytes, .bool, .enum_ => {
                try w.print("        try writer.set{s}(self.{s});\n", .{ name_camel, info.name });
            },
            .b64 => {
                try w.print("        try writer.{s}Set(self.{s});\n", .{ name_lower, info.name });
            },
            .table => {
                try w.print("        if (self.{s}) |child| {{\n", .{info.name});
                try w.writeAll("            const child_off = try child.marshalTo(alloc, out);\n");
                try w.print("            try writer.set{s}(child_off);\n", .{name_camel});
                try w.writeAll("        }\n");
            },
            .array => {
                const child = comptime schema.childOfArray(info.ty);
                const child_kind = comptime schema.kindOf(child);
                switch (child_kind) {
                    .table => {
                        try w.print("        if (self.{s}.len > 0) {{\n", .{info.name});
                        try w.print("            const offsets = try alloc.alloc(u32, self.{s}.len);\n", .{info.name});
                        try w.writeAll("            defer alloc.free(offsets);\n");
                        try w.print("            for (self.{s}, 0..) |child, ci| {{\n", .{info.name});
                        try w.writeAll("                offsets[ci] = try child.marshalTo(alloc, out);\n");
                        try w.writeAll("            }\n");
                        try w.print("            try writer.set{s}(offsets);\n", .{name_camel});
                        try w.writeAll("        }\n");
                    },
                    .u16, .u32, .u64, .b64 => {
                        try w.print("        if (self.{s}.len > 0) try writer.set{s}(self.{s});\n", .{ info.name, name_camel, info.name });
                    },
                    else => @compileError("unsupported array child kind in struct marshalTo"),
                }
            },
        }
    }
    try w.writeAll("        const result = try writer.finish();\n");
    try w.writeAll("        return result.offset;\n");
    try w.writeAll("    }\n");

    try w.writeAll("};\n\n");
}

